def _cpf(rng: random.Random) -> str:
    base = [rng.randint(0, 9) for _ in range(9)]
    for _ in range(2):
        weight = len(base) + 1
        rest = (sum(d * (weight - i) for i, d in enumerate(base)) * 10) % 11
        base.append(0 if rest == 10 else rest)
    return format_cpf("".join(map(str, base)))


def _cnpj(rng: random.Random) -> str:
    base = [rng.randint(0, 9) for _ in range(8)] + [0, 0, 0, 1]
    weights = [6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]
    for _ in range(2):
        w = weights[-len(base) :]
        rest = sum(d * x for d, x in zip(base, w, strict=True)) % 11
        base.append(0 if rest < 2 else 11 - rest)
    return format_cnpj("".join(map(str, base)))


def _cnj(rng: random.Random, year: int, segment: str, court: str) -> str:
    seq = f"{rng.randint(1, 9_999_999):07d}"
    origin = f"{rng.randint(1, 999):04d}"
    dd = cnj_check_digits(seq, str(year), segment, court, origin)
    return f"{seq}-{dd}.{year}.{segment}.{court}.{origin}"


def _person(rng: random.Random) -> str:
    return f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)} {rng.choice(LAST_NAMES)}"


def _money(rng: random.Random, low: int, high: int) -> str:
    value = rng.randint(low, high) + rng.randint(0, 99) / 100
    integer, cents = f"{value:.2f}".split(".")
    return "R$ " + f"{int(integer):,}".replace(",", ".") + "," + cents


def _date(rng: random.Random) -> str:
    d = date(2025, 1, 1) + timedelta(days=rng.randint(0, 600))
    return d.strftime("%d/%m/%Y")


