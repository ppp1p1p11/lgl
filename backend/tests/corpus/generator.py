# --- Rendering ----------------------------------------------------------------------------

_FONT, _SIZE, _LEADING = "Helvetica", 11, 15
_MARGIN = 2.5 * cm


def _page_lines(text: str) -> list[str]:
    width = A4[0] - 2 * _MARGIN
    lines: list[str] = []
    for paragraph in text.split("\n"):
        lines.extend(simpleSplit(paragraph, _FONT, _SIZE, width) or [""])
    return lines


def ground_truth(doc: SyntheticDocument) -> list[str]:
    """Exactly what each rendered page contains, line by line."""
    return ["\n".join(_page_lines(page)) for page in doc.pages]


def render_pdf(doc: SyntheticDocument) -> bytes:
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    c.setTitle(doc.title)
    for page in doc.pages:
        y = A4[1] - _MARGIN
        c.setFont(_FONT, _SIZE)
        for line in _page_lines(page):
            c.drawString(_MARGIN, y, line)
            y -= _LEADING
        c.showPage()
    c.save()
    return buffer.getvalue()


def _degrade(
    image: Image.Image, rng: random.Random, angle: float, noise: int, blur: float
) -> Image.Image:
    gray = image.convert("L").rotate(angle, resample=Image.Resampling.BICUBIC, fillcolor=255)
    if blur:
        gray = gray.filter(ImageFilter.GaussianBlur(blur))
    if noise:
        pixels = gray.load()
        assert pixels is not None
        w, h = gray.size
        for _ in range(w * h // 60):
            x, y = rng.randrange(w), rng.randrange(h)
            value = pixels[x, y]
            assert isinstance(value, int)
            pixels[x, y] = max(0, min(255, value + rng.randint(-noise, noise)))
    return gray


def render_scan(doc: SyntheticDocument, quality: str = "good", seed: int = 1) -> bytes:
    """An image-only PDF that imitates a scanned printout."""
    settings = {
        "good": (200, 0.6, 60, 0.0, 75),
        "poor": (150, 1.5, 120, 0.6, 45),
        "bad": (100, 3.0, 170, 1.2, 25),
    }
    dpi, angle, noise, blur, jpeg_quality = settings[quality]
    rng = random.Random(seed)
    pdf = pdfium.PdfDocument(render_pdf(doc))
    images = []
    for i in range(len(pdf)):
        bitmap = pdf[i].render(scale=dpi / 72)
        img = _degrade(bitmap.to_pil(), rng, rng.choice([-1, 1]) * angle, noise, blur)
        # JPEG round-trip adds realistic compression artifacts.
        tmp = io.BytesIO()
        img.save(tmp, format="JPEG", quality=jpeg_quality)
        images.append(Image.open(io.BytesIO(tmp.getvalue())).convert("L"))
    pdf.close()
    out = io.BytesIO()
    images[0].save(out, format="PDF", save_all=True, append_images=images[1:], resolution=dpi)
    return out.getvalue()


def render_photo(doc: SyntheticDocument) -> bytes:
    """First page as a JPEG, like a phone photo of a printed page."""
    pdf = pdfium.PdfDocument(render_pdf(doc))
    img = _degrade(pdf[0].render(scale=200 / 72).to_pil(), random.Random(3), 0.8, 40, 0.3)
    pdf.close()
    out = io.BytesIO()
    img.save(out, format="JPEG", quality=80)
    return out.getvalue()


def render_docx(doc: SyntheticDocument) -> bytes:
    document = docx.Document()
    for page in doc.pages:
        for paragraph in page.split("\n"):
            document.add_paragraph(paragraph)
    out = io.BytesIO()
    document.save(out)
    return out.getvalue()
